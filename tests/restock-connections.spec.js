import { test, expect } from './fixtures';
import { initialState } from '../src/model';

for (const width of [440, 1280]) test(`restock task is placed beside its item with a dotted connection at ${width}px`, async ({ page }) => {
  const state = initialState();
  const item = { id: 'bedroom-tissues', name: 'Tissues', roomId: 'bedroom1', x: 28, y: 60, quantity: 1, lowAt: 2, status: 'low', buyerId: null };
  state.inventory.push(item);
  await page.setViewportSize({ width, height: 956 });
  await page.addInitScript(value => { if (!localStorage.getItem('roomie-v1')) localStorage.setItem('roomie-v1', JSON.stringify(value)); }, state);
  await page.goto('/');
  await page.getByRole('button', { name: 'Open Jessalyn’s room', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.locator('[data-item="bedroom-tissues"]').click();
  await dialog.getByRole('button', { name: 'Restock task', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: 'Restock Tissues', exact: true })).toBeVisible();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('roomie-v1')));
  const task = saved.tasks.find(t => t.inventoryId === 'bedroom-tissues');
  const object = saved.objects.find(o => o.id === task.objectId);
  expect(object.x).toBe(56); expect(object.y).toBe(60);
  expect(saved.inventory.find(i => i.id === item.id)).toMatchObject({ x: 28, y: 60 });
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  const link = dialog.locator('[data-linked-item="bedroom-tissues"]');
  await expect(link).toHaveAttribute('data-linked-object', task.objectId);
  await expect(link).toHaveCSS('stroke-dasharray', '1px, 4px');
  await expect(dialog.locator('[data-linked-item="stock-soap"]')).toHaveCount(0);
  await dialog.evaluate(async el => { await Promise.allSettled(el.getAnimations().map(a => a.finished)); });
  await page.screenshot({ path: `test-results/restock-connection-${width}.png` });
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await expect(page.locator('.map-page [data-linked-item="bedroom-tissues"]')).toHaveAttribute('data-linked-object', task.objectId);
  await page.reload();
  await expect(page.locator('.map-page [data-linked-item="bedroom-tissues"]')).toHaveCount(1);
  await page.locator(`.map-page [data-object="${task.objectId}"]`).click();
  await dialog.getByRole('button', { name: 'I’ll take this', exact: true }).click();
  await dialog.getByRole('button', { name: 'Mark complete', exact: true }).click();
  await dialog.getByLabel('Quantity restocked', { exact: true }).fill('2');
  await dialog.getByRole('button', { name: 'Confirm restock' }).click();
  await expect(page.locator('[data-linked-item="bedroom-tissues"]')).toHaveCount(0);
  await expect(page.locator('.map-page [data-item="bedroom-tissues"]')).toBeVisible();
});
