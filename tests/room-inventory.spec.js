const nav = page => page.getByRole('navigation', { name: 'Mobile navigation' });

test('room counts and Inventory stay synchronized and persist across reloads', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Open Bathroom', exact: true }).click({ position: { x: 8, y: 8 } });
  const dialog = page.getByRole('dialog');
  await dialog.evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished.catch(() => {}))); });
  await dialog.locator('[data-item="stock-paper"]').click();
  await dialog.evaluate(async el => { await Promise.allSettled(el.getAnimations().map(a => a.finished)); });
  const roomSize = await dialog.boundingBox();
  await dialog.getByRole('button', { name: 'Set quantity for Toilet paper' }).click();
  await dialog.getByLabel('Quantity (optional)').fill('8');
  await dialog.getByLabel('Unit', { exact: true }).fill('rolls');
  await dialog.getByLabel('Low stock at or below').fill('2');
  await dialog.getByLabel('Storage spot (optional)').fill('Under the sink');
  await dialog.getByRole('button', { name: 'Save item' }).click();
  await expect(dialog.getByRole('heading', { name: 'Toilet paper', exact: true })).toBeVisible();
  expect((await dialog.boundingBox()).height).toBeLessThan(720);
  await dialog.evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished.catch(() => {}))); });
  expect((await dialog.boundingBox()).width).toBe(roomSize.width);
  const paper = dialog;
  await expect(paper.locator('output')).toHaveText('8 rolls');
  await expect(paper.getByText('Under the sink')).toBeVisible();
  await page.screenshot({ path: 'test-results/room-inventory-mobile.png' });
  await paper.getByRole('button', { name: 'Use one Toilet paper' }).click();
  await expect(paper.locator('output')).toHaveText('7 rolls');
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await nav(page).getByRole('button', { name: 'Inventory', exact: true }).click();
  const inventoryPaper = page.getByRole('article', { name: 'Toilet paper', exact: true });
  await expect(inventoryPaper.getByRole('status')).toHaveText('7 rolls');
  await inventoryPaper.getByRole('button', { name: 'Add one Toilet paper' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Open Bathroom', exact: true }).click({ position: { x: 8, y: 8 } });
  await dialog.locator('[data-item="stock-paper"]').click();
  await expect(paper.locator('output')).toHaveText('8 rolls');
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.screenshot({ path: 'test-results/room-inventory-desktop.png' });
});

test('a new room supply can create a linked restock task without duplicating it', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Open Living room', exact: true }).click({ position: { x: 8, y: 8 } });
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Add item' }).click();
  await dialog.getByLabel('Item name').fill('Candles');
  await dialog.getByLabel('Quantity (optional)').fill('1');
  await dialog.getByRole('button', { name: 'Add item', exact: true }).click();
  await dialog.getByRole('button', { name: 'Confirm', exact: true }).click();
  await dialog.locator('.supply-map-pin').click();
  await dialog.getByRole('button', { name: 'Restock task' }).click();
  await expect(dialog.getByRole('heading', { name: 'Restock Candles', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await expect(dialog.getByRole('heading', { name: 'Candles', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await expect(dialog.getByRole('button', { name: 'Candles in Living room, needs attention' })).toBeVisible();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Open Living room', exact: true }).click({ position: { x: 8, y: 8 } });
  await dialog.locator('.supply-map-pin').click();
  await dialog.getByRole('button', { name: 'Restock task' }).click();
  await expect(dialog.getByRole('heading', { name: 'Restock Candles', exact: true })).toBeVisible();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('roomie-v1')));
  const item = saved.inventory.find(i => i.name === 'Candles');
  const tasks = saved.tasks.filter(t => t.inventoryId === item.id);
  expect(tasks).toHaveLength(1);
  expect(tasks[0].objectId).toBe(item.objectId);
});

