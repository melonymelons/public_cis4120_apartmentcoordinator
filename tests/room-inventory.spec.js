for (const viewport of [{ width: 390, height: 844 }, { width: 1280, height: 900 }]) {
  test(`room popup fits room proportions at ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport);
    await page.goto('/');
    await page.evaluate(() => document.fonts.ready);
    const sizes = {};
    for (const name of ['Bathroom', 'Kitchen', 'Living room']) {
      await page.getByRole('button', { name: `Open ${name}`, exact: true }).click({ position: { x: 8, y: 8 } });
      const dialog = page.getByRole('dialog');
      const bounds = await dialog.boundingBox();
      sizes[name] = bounds;
      expect(bounds.height).toBeLessThanOrEqual(viewport.height - 32);
      expect(bounds.width).toBeLessThanOrEqual(viewport.width - 32);
      expect(bounds.y).toBeGreaterThanOrEqual(15);
      const detail = await dialog.locator('.room-detail').boundingBox();
      expect(bounds.y + bounds.height - detail.y - detail.height).toBeLessThan(40);
      await page.screenshot({ path: `test-results/room-fit-${name.replaceAll(' ', '-')}-${viewport.width}.png` });
      await dialog.getByRole('button', { name: 'Close dialog' }).click();
    }
    expect(sizes.Bathroom.height).toBeLessThan(sizes.Kitchen.height);
    expect(sizes.Bathroom.height).toBeLessThan(sizes['Living room'].height);
    if (viewport.width > 640) expect(sizes.Kitchen.width).toBeLessThan(600);
  });
}
