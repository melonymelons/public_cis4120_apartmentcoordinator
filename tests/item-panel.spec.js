import { test, expect } from './fixtures';
import { initialState } from '../src/model';

for (const width of [320, 440, 1280]) test(`item options open only after tapping an item at ${width}px`, async ({ page }) => {
  const state = initialState();
  state.inventory = state.inventory.map(item => item.id === 'stock-paper' ? { ...item, quantity: 3, status: 'in', unit: 'rolls' } : item);
  await page.setViewportSize({ width, height: 956 });
  await page.addInitScript(value => { if (!localStorage.getItem('roomie-v1')) localStorage.setItem('roomie-v1', JSON.stringify(value)); }, state);
  await page.goto('/');
  await page.locator('.map-page [data-item="stock-paper"]').click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('heading', { name: 'Toilet paper', exact: true })).toBeVisible();
  await expect(dialog.locator('.room-focus-map')).toHaveCount(0);
  await expect(dialog.locator('output')).toHaveText('3 rolls');
  await dialog.getByRole('button', { name: 'Edit Toilet paper' }).click();
  await dialog.getByLabel('Item name').fill('Changed name');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: 'Toilet paper', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: 'Open Bathroom', exact: true }).click();
  await expect(dialog.locator('.room-focus-map')).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Restock task' })).toHaveCount(0);
  await expect(dialog.locator('.quantity-stepper,.room-supply-inspector')).toHaveCount(0);
  await dialog.locator('[data-item="stock-paper"]').click();
  await dialog.getByRole('button', { name: 'Use one Toilet paper' }).click();
  await expect(dialog.locator('output')).toHaveText('2 rolls');
  await dialog.evaluate(async el => { await Promise.allSettled(el.getAnimations().map(a => a.finished)); });
  await page.screenshot({ path: `test-results/item-detail-${width}.png` });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await dialog.getByRole('button', { name: 'Restock task', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: 'Restock toilet paper', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await expect(dialog.getByRole('heading', { name: 'Toilet paper', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await expect(dialog.getByRole('heading', { name: 'Bathroom', exact: true })).toBeVisible();
  await expect(dialog.locator('.quantity-stepper')).toHaveCount(0);
  await expect(dialog.locator('[data-item="stock-paper"]')).toContainText('2');
});
