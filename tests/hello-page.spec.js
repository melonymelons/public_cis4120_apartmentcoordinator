import { test, expect } from './fixtures';
import { ICON_NAMES } from '../src/Icons';

for (const width of [320, 390, 1280]) test(`diamond opens collapsible Hello demos and returns to the same app at ${width}px`, async ({ page, browserName }) => {
  await page.setViewportSize({ width, height: 900 });
  await page.goto('/');
  const before = await page.evaluate(() => localStorage.getItem('roomie-v1'));
  await page.evaluate(() => document.fonts.ready);
  const originalLogo = await page.locator('.app-header .brand').boundingBox();
  const star = page.getByRole('link', { name: 'Open Hello world and style guide' });
  await expect(star).toBeInViewport();
  await expect(star.locator('.demo-diamond')).toBeVisible();
  await expect(star.locator('.demo-diamond>svg')).toHaveCSS('animation-name', /diamond-hop/);
  await expect(star.locator('.diamond-glint').first()).toHaveCSS('animation-name', 'diamond-glitter');
  await star.click();
  await expect(page).toHaveURL(/#hello$/);
  const styleLogo = await page.locator('.hello-page-header .brand').boundingBox();
  for (const key of ['x', 'y', 'width', 'height']) expect(styleLogo[key], key).toBeCloseTo(originalLogo[key], 0);
  const demo = page.getByRole('main');
  await expect(demo.getByText('Hello world', { exact: true })).toHaveCount(2);
  await expect(page.getByRole('heading', { name: 'Hello styles', exact: true })).toBeVisible();
  await expect(page.locator('.hello-karla').first()).toHaveCSS('font-family', /Karla/);
  await expect(page.locator('.hello-inter').first()).toHaveCSS('font-family', /Inter/);
  await expect(page.locator('.hello-icons li')).toHaveCount(ICON_NAMES.length);
  expect(await page.locator('.hello-page').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: `test-results/hello-${browserName}-${width}.png` });
  await page.getByRole('button', { name: 'Collapse all', exact: true }).click();
  await expect(page.locator('.hello-world-output')).toBeHidden();
  await expect(page.locator('.hello-fonts')).toBeHidden();
  await page.getByText('Fonts', { exact: true }).click();
  await expect(page.locator('.hello-fonts')).toBeVisible();
  await page.getByRole('button', { name: 'Expand all', exact: true }).click();
  await expect(page.locator('.hello-icons')).toBeVisible();
  await expect(page.locator('.hello-world-output')).toBeVisible();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(page.locator('.hello-page-header .diamond-glint').first()).toHaveCSS('animation-name', 'none');
  await page.getByRole('link', { name: 'Back to nest.', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Apartment canvas' })).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem('roomie-v1'))).toBe(before);
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'Hello styles', exact: true })).toBeVisible();
});
