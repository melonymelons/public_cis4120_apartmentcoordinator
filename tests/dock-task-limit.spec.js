import { test, expect } from './fixtures';
import { initialState } from '../src/model';

for (const width of [320, 390, 1280]) test(`availability layers page through four tasks with independent arrows at ${width}px`, async ({ page }) => {
  const state = initialState();
  state.tasks.push(...Array.from({ length: 8 }, (_, index) => ({ id: `assigned-${index}`, objectId: 'trash1', title: `Assigned task ${index + 1}`, status: 'assigned', from: 'jess', to: 'maya' })));
  state.tasks.push(...Array.from({ length: 5 }, (_, index) => ({ id: `pending-${index}`, objectId: 'supplies1', title: `Pending task ${index + 1}`, status: 'pending', from: 'jess', to: 'alex' })));
  await page.setViewportSize({ width, height: 900 });
  await page.addInitScript(value => { if (!localStorage.getItem('roomie-v1')) localStorage.setItem('roomie-v1', JSON.stringify(value)); }, state);
  await page.goto('/');
  const dock = page.getByRole('complementary', { name: 'Roommate availability dock' });
  await expect(dock.locator('.tray-task').first()).toBeHidden();
  await dock.getByRole('button', { name: 'Expand availability', exact: true }).click();
  await expect(page.locator('.dock-drag-hint')).toBeVisible();
  const maya = dock.locator('[data-person="maya"]'), alex = dock.locator('[data-person="alex"]');
  await expect(maya.locator('.tray-task')).toHaveCount(4);
  await expect(alex.locator('.tray-task')).toHaveCount(4);
  const icons = await maya.locator('.tray-task').evaluateAll(elements => elements.map(el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; }));
  for (const icon of icons) expect(icon.y + icon.height / 2).toBeCloseTo(icons[0].y + icons[0].height / 2, 0);
  const previous = await maya.getByRole('button', { name: 'Previous tasks for Maya' }).boundingBox();
  const next = await maya.getByRole('button', { name: 'Next tasks for Maya' }).boundingBox();
  expect(previous.x + previous.width).toBeLessThanOrEqual(icons[0].x);
  expect(next.x).toBeGreaterThanOrEqual(icons[3].x + icons[3].width);
  expect(previous.y + previous.height / 2).toBeCloseTo(icons[0].y + icons[0].height / 2, 0);
  await expect(maya.getByRole('button', { name: 'Previous tasks for Maya' })).toBeDisabled();
  await maya.getByRole('button', { name: 'Next tasks for Maya' }).click();
  await expect(maya.locator('.tray-task')).toHaveCount(4);
  await expect(maya.getByRole('button', { name: 'Assigned task 8, accepted by Maya', exact: true })).toBeVisible();
  await expect(maya.getByRole('button', { name: 'Next tasks for Maya' })).toBeDisabled();
  await expect(maya.getByRole('status')).toHaveText('Page 2 of 2 for Maya');
  await expect(alex.locator('.tray-task')).toHaveCount(4);
  const alexHeight = (await alex.boundingBox()).height;
  await alex.getByRole('button', { name: 'Next tasks for Alex' }).click();
  await expect(alex.locator('.tray-task')).toHaveCount(1);
  expect((await alex.boundingBox()).height).toBeCloseTo(alexHeight, 0);
  expect(await dock.locator('.dock-trays').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: `test-results/dock-task-limit-${width}.png` });
  await maya.getByRole('button', { name: 'Previous tasks for Maya' }).click();
  await expect(maya.getByRole('button', { name: 'Assigned task 1, accepted by Maya', exact: true })).toBeVisible();
  await dock.getByRole('button', { name: 'Collapse availability', exact: true }).click();
  await dock.getByRole('button', { name: 'Expand availability', exact: true }).click();
  await expect(alex.locator('.tray-task')).toHaveCount(4);
  await maya.getByRole('button', { name: 'Next tasks for Maya' }).click();
  await maya.getByRole('button', { name: 'Assigned task 8, accepted by Maya', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('heading', { name: 'Assigned task 8', exact: true })).toBeVisible();
});
