import { test, expect } from './fixtures';
import { initialState } from '../src/model';

test('in-stock items can be restocked; completion deletes the task and marker, supports undo, and permits another restock', async ({ page }) => {
  const state = initialState();
  state.inventory = state.inventory.map(item => item.id === 'stock-paper' ? { ...item, quantity: 8, unit: 'rolls', status: 'in', x: 32, y: 70 } : item);
  await page.addInitScript(value => { if (!localStorage.getItem('roomie-v1')) localStorage.setItem('roomie-v1', JSON.stringify(value)); }, state);
  await page.goto('/');
  await page.locator('.map-page [data-item="stock-paper"]').click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('button', { name: 'Restock task' })).toBeVisible();
  await dialog.getByRole('button', { name: 'Restock task' }).click();
  await dialog.getByRole('button', { name: 'I’ll take this' }).click();
  await dialog.getByRole('button', { name: 'Mark complete' }).click();
  await dialog.getByLabel('Quantity restocked', { exact: true }).fill('5');
  await dialog.getByRole('button', { name: 'Confirm restock' }).click();
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('roomie-v1')));
  let value = await saved();
  expect(value.tasks.some(task => task.id === 'task-supplies')).toBe(false);
  expect(value.objects.some(object => object.id === 'supplies1')).toBe(false);
  expect(value.inventory.find(item => item.id === 'stock-paper')).toMatchObject({ quantity: 13, x: 32, y: 70, objectId: null });
  await expect(page.locator('[data-linked-item="stock-paper"]')).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  value = await saved();
  expect(value.tasks.find(task => task.id === 'task-supplies')).toMatchObject({ status: 'assigned', inventoryId: 'stock-paper' });
  expect(value.objects.some(object => object.id === 'supplies1')).toBe(true);
  await dialog.getByRole('button', { name: 'Restock task' }).click();
  await dialog.getByRole('button', { name: 'Mark complete' }).click();
  await dialog.getByLabel('Quantity restocked', { exact: true }).fill('2');
  await dialog.getByRole('button', { name: 'Confirm restock' }).click();
  await dialog.getByRole('button', { name: 'Restock task' }).click();
  await expect(dialog.getByRole('heading', { name: 'Restock Toilet paper', exact: true })).toBeVisible();
  value = await saved();
  expect(value.tasks.filter(task => task.inventoryId === 'stock-paper')).toHaveLength(1);
  const newTask = value.tasks.find(task => task.inventoryId === 'stock-paper');
  expect(newTask.id).not.toBe('task-supplies');
  await dialog.getByRole('button', { name: 'I’ll take this' }).click();
  await dialog.getByRole('button', { name: 'Mark complete' }).click();
  await dialog.getByLabel('Quantity restocked', { exact: true }).fill('3');
  await dialog.getByRole('button', { name: 'Confirm restock' }).click();
  await page.reload();
  value = await saved();
  expect(value.tasks.some(task => task.inventoryId === 'stock-paper')).toBe(false);
  expect(value.objects.some(object => object.id === newTask.objectId)).toBe(false);
  await expect(page.locator('.map-page [data-item="stock-paper"]')).toContainText('13');
});
