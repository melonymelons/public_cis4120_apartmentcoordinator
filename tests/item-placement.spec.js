import { test, expect } from './fixtures';

for (const width of [390, 1280]) test(`item placement supports dragging, Back, persistence and repositioning at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 956 });
  await page.goto('/');
  await page.locator(width > 640 ? '.desktop-nav' : '.mobile-nav').getByRole('button', { name: 'Inventory', exact: true }).click();
  await page.getByRole('button', { name: 'Add item', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Item name').fill('Laundry detergent');
  await dialog.getByLabel('Quantity (optional)').fill('2');
  await dialog.getByLabel('Unit', { exact: true }).fill('bottles');
  await dialog.getByLabel('Room', { exact: true }).click();
  await dialog.getByRole('option', { name: 'Living room', exact: true }).click();
  await dialog.getByRole('button', { name: 'Add item', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: 'Place item', exact: true })).toBeVisible();
  const marker = dialog.getByRole('button', { name: 'Position Laundry detergent' });
  await expect(marker).toHaveClass(/inventory-marker/);
  await marker.focus(); await page.keyboard.press('ArrowRight');
  const box = await marker.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 30, box.y + box.height / 2 + 15, { steps: 5 }); await page.mouse.up();
  const point = await marker.evaluate(el => ({ x: parseFloat(el.style.left), y: parseFloat(el.style.top) }));
  await dialog.getByRole('button', { name: 'Back', exact: true }).click();
  await expect(dialog.getByLabel('Item name')).toHaveValue('Laundry detergent');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('roomie-v1')).inventory.some(item => item.name === 'Laundry detergent'))).toBe(false);
  await dialog.getByRole('button', { name: 'Add item', exact: true }).click();
  expect(await marker.evaluate(el => ({ x: parseFloat(el.style.left), y: parseFloat(el.style.top) }))).toEqual(point);
  await dialog.evaluate(async el => { await Promise.allSettled(el.getAnimations().map(a => a.finished)); });
  await page.screenshot({ path: `test-results/item-placement-${width}.png` });
  await dialog.getByRole('button', { name: 'Confirm', exact: true }).click();
  const item = await page.evaluate(() => JSON.parse(localStorage.getItem('roomie-v1')).inventory.find(item => item.name === 'Laundry detergent'));
  expect(item).toMatchObject({ quantity: 2, roomId: 'living' });
  expect(item.x).toBeCloseTo(point.x, 3);
  expect(item.y).toBeCloseTo(point.y, 3);
  await page.getByRole('link', { name: 'nest.', exact: true }).click();
  const pin = page.locator(`.map-page [data-item="${item.id}"]`);
  expect(await pin.evaluate(el => ({ x: parseFloat(el.style.left), y: parseFloat(el.style.top) }))).toEqual(point);
  await pin.click();
  await dialog.getByRole('button', { name: 'Edit Laundry detergent' }).click();
  await dialog.getByRole('button', { name: 'Change placement' }).click();
  await marker.focus(); await page.keyboard.press('ArrowLeft');
  const moved = await marker.evaluate(el => parseFloat(el.style.left));
  await dialog.getByRole('button', { name: 'Confirm', exact: true }).click();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await page.reload();
  expect(await pin.evaluate(el => parseFloat(el.style.left))).toBe(moved);
});
