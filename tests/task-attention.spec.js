import { test, expect } from './fixtures';
import { enterEdit } from './layout-helpers';

for (const context of ['map', 'To-dos']) test(`new tasks start yellow and can be flagged explicitly from ${context}`, async ({ page }) => {
  await page.goto('/');
  if (context === 'map') await enterEdit(page);
  else await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('button', { name: context, exact: true }).click();
  await page.getByRole('button', { name: 'Add task', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Task name').fill('Water plants');
  await dialog.getByRole('button', { name: 'Add to apartment' }).click();
  await dialog.getByRole('button', { name: 'Confirm', exact: true }).click();
  if (context === 'map') await page.getByRole('button', { name: 'Done', exact: true }).click();
  else await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('button', { name: 'Apartment', exact: true }).click();
  const yellow = page.getByRole('button', { name: 'Water plants in Kitchen, open', exact: true });
  await expect(yellow).toBeVisible();
  await expect(yellow).not.toHaveClass(/needs-attention/);
  await expect(yellow).toHaveCSS('background-color', 'rgb(255, 228, 162)');
  await expect(yellow).toHaveCSS('animation-name', 'none');
  await yellow.click();
  await expect(dialog.locator('.object-selected-task')).toHaveCount(0);
  await expect(dialog.locator('.add-actions')).toHaveCount(0);
  await expect(dialog.getByRole('button', { name: 'Edit task', exact: true })).toHaveCount(0);
  await expect(dialog.getByRole('button', { name: 'Remove', exact: true })).toHaveCount(1);
  await expect(dialog.getByLabel('What needs doing?')).toHaveValue('Water plants');
  await dialog.screenshot({ path: `test-results/yellow-task-${context}.png` });
  await dialog.getByRole('button', { name: 'Flag for attention', exact: true }).click();
  await expect(dialog.getByLabel('What needs doing?')).toHaveCount(0);
  await expect(dialog.getByRole('button', { name: 'I’ll take this', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  const pink = page.getByRole('button', { name: 'Water plants in Kitchen, needs attention', exact: true });
  await expect(pink).toHaveClass(/needs-attention/);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(yellow).toBeVisible();
  await yellow.click();
  await dialog.getByRole('button', { name: 'Flag for attention', exact: true }).click();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await page.reload();
  await expect(pink).toHaveClass(/needs-attention/);
});
